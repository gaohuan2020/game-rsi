let currentLanguage = localStorage.getItem('game-rsi-language') || 'zh-CN';
if (!messages[currentLanguage]) currentLanguage = 'zh-CN';
function t(source, values={}) {
  const text = messages[currentLanguage][source] ?? source;
  return text.replace(/\{(\w+)\}/g, (match,key) => String(values[key] ?? match));
}
const staticText = [];
const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
while (walker.nextNode()) {
  const node = walker.currentNode, source = node.textContent.trim();
  if (!node.parentElement.closest('script,style') && (source in messages.en || source in messages['zh-CN'])) {
    staticText.push({node, source, prefix:node.textContent.match(/^\s*/)[0], suffix:node.textContent.match(/\s*$/)[0]});
  }
}
const staticAttributes = [];
for (const element of document.querySelectorAll('[aria-label],[alt],[title],meta[name="description"]')) {
  for (const attribute of ['aria-label','alt','title','content']) {
    const source=element.getAttribute(attribute);
    if (source && (source in messages.en || source in messages['zh-CN'])) staticAttributes.push({element,attribute,source});
  }
}
const titleSource = document.title;
function setLanguage(language) {
  currentLanguage = messages[language] ? language : 'zh-CN';
  localStorage.setItem('game-rsi-language',currentLanguage);
  document.documentElement.lang=currentLanguage;
  document.title=t(titleSource);
  for (const item of staticText) if (item.node.isConnected) item.node.textContent=item.prefix+t(item.source)+item.suffix;
  for (const item of staticAttributes) if (item.element.isConnected) item.element.setAttribute(item.attribute,t(item.source));
  document.getElementById('language-select').value=currentLanguage;
  document.dispatchEvent(new CustomEvent('languagechange'));
}
document.getElementById('language-select').addEventListener('change',event=>setLanguage(event.target.value));
setLanguage(currentLanguage);
